//! Renders a plan as a POSIX shell script using the git dialect.

use std::fmt::Write;
use std::path::Path;

use crate::plan::{Plan, Step};
use crate::render::message::sync_message;
use crate::render::{heredoc_delim, last_component, sh_quote, short};

/// The default branch name for the git dialect: `quickpick/<last component>`.
pub fn default_branch(path: &str) -> String {
    format!("quickpick/{}", last_component(path))
}

/// Render `plan` as a self-contained POSIX shell script. All interpolated
/// values name resolved commit ids, so the script applies exactly what was
/// simulated. An empty plan renders as an empty string.
pub fn render(plan: &Plan, branch: &str, repo_root: &Path) -> String {
    if plan.steps.is_empty() {
        return String::new();
    }
    let mut out = format!(
        "#!/bin/sh\n\
         # Generated by quickpick: sync {} from {} ({}) onto {} ({}).\n\
         set -eu\n\
         cd -- {}\n\
         git switch -c {} {}\n",
        plan.path,
        plan.source_rev,
        short(plan.to),
        plan.onto_rev,
        short(plan.onto),
        sh_quote(&repo_root.to_string_lossy()),
        sh_quote(branch),
        plan.onto,
    );
    for step in &plan.steps {
        match step {
            Step::Pick { commit } => {
                let _ = writeln!(out, "# PICK {} {}", short(commit.id), commit.summary);
                let _ = writeln!(out, "git cherry-pick -x {}", commit.id);
            }
            Step::Sync {
                target,
                covered,
                removes_path,
            } => {
                let _ = writeln!(
                    out,
                    "# SYNC {} ({} {})",
                    short(target.id),
                    covered.len(),
                    if covered.len() == 1 {
                        "commit"
                    } else {
                        "commits"
                    },
                );
                let _ = writeln!(
                    out,
                    "git rm -r -q --ignore-unmatch -- {}",
                    sh_quote(&plan.path)
                );
                if !removes_path {
                    let _ = writeln!(
                        out,
                        "git checkout {} -- {}",
                        target.id,
                        sh_quote(&plan.path)
                    );
                }
                let msg = sync_message(plan, step).unwrap_or_default();
                let delim = heredoc_delim(&msg);
                let _ = writeln!(out, "git commit -q --allow-empty -F - <<'{delim}'");
                out.push_str(&msg);
                let _ = writeln!(out, "{delim}");
            }
        }
    }
    out
}

#[cfg(test)]
pub mod tests {
    use super::*;
    use crate::plan::Reason;
    use crate::render::message::tests::{commit, plan};
    use std::io::Write as _;
    use std::process::{Command, Stdio};

    /// `sh -n` syntax check; skipped when `sh` is not on PATH.
    pub fn sh_check(script: &str) {
        let Ok(mut cmd) = Command::new("sh").arg("-n").stdin(Stdio::piped()).spawn() else {
            return;
        };
        cmd.stdin
            .as_mut()
            .unwrap()
            .write_all(script.as_bytes())
            .unwrap();
        assert!(cmd.wait().unwrap().success(), "sh -n rejected:\n{script}");
    }

    fn mixed_plan() -> Plan {
        let mut p = plan("pkgs/by-name/op/openai");
        let pick = commit(0x11, "openai: 1.0 -> 1.1");
        let s1 = commit(0x12, "openai: 1.1 -> 1.2");
        let s2 = commit(0x13, "openai: 1.2 -> 1.3");
        p.steps = vec![
            Step::Pick { commit: pick },
            Step::Sync {
                target: s2.clone(),
                covered: vec![
                    (s1, Reason::OutsidePaths(vec!["other/file".into()])),
                    (
                        s2,
                        Reason::Conflict(vec!["pkgs/by-name/op/openai/f".into()]),
                    ),
                ],
                removes_path: false,
            },
        ];
        p
    }

    #[test]
    fn full_script_for_a_mixed_plan() {
        let script = render(&mixed_plan(), "quickpick/openai", Path::new("/tmp/repo"));
        let expected = "\
#!/bin/sh
# Generated by quickpick: sync pkgs/by-name/op/openai from master (0000004) onto release-26.05 (0000002).
set -eu
cd -- '/tmp/repo'
git switch -c 'quickpick/openai' 0000002000000000000000000000000000000000
# PICK 0000011 openai: 1.0 -> 1.1
git cherry-pick -x 0000011000000000000000000000000000000000
# SYNC 0000013 (2 commits)
git rm -r -q --ignore-unmatch -- 'pkgs/by-name/op/openai'
git checkout 0000013000000000000000000000000000000000 -- 'pkgs/by-name/op/openai'
git commit -q --allow-empty -F - <<'QUICKPICK_EOF'
openai: sync to 0000013 (openai: 1.2 -> 1.3)

Not cherry-picked. Sets pkgs/by-name/op/openai to its state at
0000013000000000000000000000000000000000 on master, replacing these source commits:

  0000012 openai: 1.1 -> 1.2
          touches files outside the path: other/file
  0000013 openai: 1.2 -> 1.3
          conflicts with the target in: pkgs/by-name/op/openai/f

Generated by quickpick.
QUICKPICK_EOF
";
        assert_eq!(script, expected);
        sh_check(&script);
    }

    #[test]
    fn quotes_paths_and_survives_quote_in_summary() {
        let mut p = plan("it's/dir");
        let t = commit(0x43, "sync it");
        p.steps = vec![
            Step::Pick {
                commit: commit(0x42, "it's quoted"),
            },
            Step::Sync {
                target: t.clone(),
                covered: vec![(t, Reason::Conflict(vec!["it's/dir/f".into()]))],
                removes_path: false,
            },
        ];
        let script = render(&p, "b", Path::new("/r"));
        assert!(script.contains("'it'\\''s/dir'"), "{script}");
        assert!(script.contains("# PICK 0000042 it's quoted"), "{script}");
        sh_check(&script);
    }

    #[test]
    fn removal_sync_has_no_checkout() {
        let mut p = plan("pkg");
        let t = commit(0x30, "remove pkg");
        p.steps = vec![Step::Sync {
            target: t,
            covered: vec![],
            removes_path: true,
        }];
        let script = render(&p, "b", Path::new("/r"));
        assert!(
            script.contains("git rm -r -q --ignore-unmatch -- 'pkg'"),
            "{script}"
        );
        assert!(!script.contains("git checkout"), "{script}");
        sh_check(&script);
    }

    #[test]
    fn empty_plan_is_empty_script() {
        assert_eq!(render(&plan("pkg"), "b", Path::new("/r")), "");
    }

    #[test]
    fn default_branch_uses_the_last_path_component() {
        assert_eq!(default_branch("pkgs/by-name/op/openai"), "quickpick/openai");
        assert_eq!(default_branch("file.nix"), "quickpick/file.nix");
    }
}
