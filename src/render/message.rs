//! Commit messages shared by both script dialects: the cherry-pick trailer
//! convention and the sync-commit format.

use std::fmt::Write;

use crate::plan::{CommitInfo, Plan, Reason, Step};
use crate::render::{last_component, short};

/// The message for a PICK: the original commit message, a blank line and
/// the `(cherry picked from commit <sha>)` trailer.
pub fn cherry_pick_message(c: &CommitInfo) -> String {
    format!(
        "{}\n\n(cherry picked from commit {})\n",
        c.message.trim_end(),
        c.id
    )
}

/// The message for a SYNC step, or `None` when `step` is a [`Step::Pick`].
///
/// ```text
/// <last component>: sync to <short target> (<target summary>)
///
/// Not cherry-picked. Sets <path> to its state at
/// <full target sha> on <source_rev>, replacing these source commits:
///
///   <short> <summary>
///           <reason>
///
/// Generated by quickpick.
/// ```
pub fn sync_message(plan: &Plan, step: &Step) -> Option<String> {
    let Step::Sync {
        target,
        covered,
        removes_path,
    } = step
    else {
        return None;
    };
    let verb = if *removes_path {
        format!("Removes {}, as at", plan.path)
    } else {
        format!("Sets {} to its state at", plan.path)
    };
    let mut out = format!(
        "{}: sync to {} ({})\n\nNot cherry-picked. {verb}\n{} on {}, replacing these source \
         commits:\n\n",
        last_component(&plan.path),
        short(target.id),
        target.summary,
        target.id,
        plan.source_rev,
    );
    for (c, reason) in covered {
        let _ = writeln!(out, "  {} {}", short(c.id), c.summary);
        let _ = writeln!(out, "          {}", reason_text(reason));
    }
    out.push_str("\nGenerated by quickpick.\n");
    Some(out)
}

/// A human-readable rendering of why a commit was synced.
pub fn reason_text(reason: &Reason) -> String {
    let (intro, paths) = match reason {
        Reason::OutsidePaths(p) => ("touches files outside the path", p),
        Reason::Conflict(p) => ("conflicts with the target in", p),
    };
    let shown: Vec<&str> = paths.iter().take(10).map(String::as_str).collect();
    let suffix = if paths.len() > shown.len() {
        format!(", and {} more", paths.len() - shown.len())
    } else {
        String::new()
    };
    format!("{intro}: {}{suffix}", shown.join(", "))
}

#[cfg(test)]
pub mod tests {
    use super::*;
    use git2::Oid;

    /// A fake commit id whose first seven hex digits are `{n}` itself, so
    /// `short()` output is recognizable in string comparisons.
    pub fn oid(n: u64) -> Oid {
        Oid::from_str(&format!("{n:07x}{:0>33}", "")).unwrap()
    }

    pub fn commit(n: u64, msg: &str) -> CommitInfo {
        CommitInfo {
            id: oid(n),
            summary: msg.lines().next().unwrap_or_default().to_string(),
            message: msg.to_string(),
            author_time: 1_700_000_000,
            author_offset_minutes: 0,
        }
    }

    pub fn plan(path: &str) -> Plan {
        Plan {
            path: path.into(),
            source_rev: "master".into(),
            onto_rev: "release-26.05".into(),
            source: oid(1),
            onto: oid(2),
            from: Some(oid(3)),
            to: oid(4),
            anchor: Some(oid(3)),
            steps: vec![],
            warnings: vec![],
            verified: true,
        }
    }

    #[test]
    fn pick_message_appends_the_trailer() {
        let c = commit(0xabc, "openai: 1.4.0 -> 1.4.1\n\nbody\n\n\n");
        assert_eq!(
            cherry_pick_message(&c),
            "openai: 1.4.0 -> 1.4.1\n\nbody\n\n(cherry picked from commit \
             0000abc000000000000000000000000000000000)\n"
        );
    }

    #[test]
    fn sync_message_single_commit() {
        let p = plan("pkgs/by-name/op/openai");
        let target = commit(0x4d5e6f7, "openai: 1.4.0 -> 1.4.1");
        let step = Step::Sync {
            target: target.clone(),
            covered: vec![(
                target.clone(),
                Reason::OutsidePaths(vec!["pkgs/top-level/python-packages.nix".into()]),
            )],
            removes_path: false,
        };
        assert_eq!(
            sync_message(&p, &step).unwrap(),
            "openai: sync to 4d5e6f7 (openai: 1.4.0 -> 1.4.1)\n\
             \n\
             Not cherry-picked. Sets pkgs/by-name/op/openai to its state at\n\
             4d5e6f7000000000000000000000000000000000 on master, replacing these source commits:\n\
             \n\
             \x20 4d5e6f7 openai: 1.4.0 -> 1.4.1\n\
             \x20         touches files outside the path: pkgs/top-level/python-packages.nix\n\
             \n\
             Generated by quickpick.\n"
        );
    }

    #[test]
    fn sync_message_merged_commits_with_both_reasons() {
        let p = plan("pkg");
        let a = commit(0xa1, "pkg: one");
        let b = commit(0xa2, "pkg: two");
        let step = Step::Sync {
            target: b.clone(),
            covered: vec![
                (a, Reason::OutsidePaths(vec!["x".into()])),
                (b, Reason::Conflict(vec!["pkg/f".into()])),
            ],
            removes_path: false,
        };
        let msg = sync_message(&p, &step).unwrap();
        assert!(msg.contains("  00000a1 pkg: one\n          touches files outside the path: x\n"));
        assert!(
            msg.contains("  00000a2 pkg: two\n          conflicts with the target in: pkg/f\n")
        );
    }

    #[test]
    fn sync_message_removal() {
        let p = plan("pkg");
        let t = commit(0x9, "drop pkg");
        let step = Step::Sync {
            target: t,
            covered: vec![],
            removes_path: true,
        };
        let msg = sync_message(&p, &step).unwrap();
        assert!(msg.contains("Not cherry-picked. Removes pkg, as at\n0000009000000000000000000000000000000000 on master"));
    }

    #[test]
    fn reason_text_caps_at_ten_paths() {
        let r = Reason::OutsidePaths((0..12).map(|i| format!("f{i}")).collect());
        let text = reason_text(&r);
        assert!(text.contains("f9"), "{text}");
        assert!(!text.contains("f10"), "{text}");
        assert!(text.ends_with("and 2 more"), "{text}");
    }
}
