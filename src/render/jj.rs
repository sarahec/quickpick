//! Renders a plan as a POSIX shell script using the jujutsu dialect.

use std::fmt::Write;
use std::path::Path;

use crate::plan::{Plan, Step};
use crate::render::message::{cherry_pick_message, sync_message};
use crate::render::{heredoc_delim, sh_quote, short};

/// Escape `path` for embedding in a double-quoted jj fileset string.
fn fileset_escape(path: &str) -> String {
    path.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Render `plan` as a self-contained POSIX shell script using jj commands.
/// An empty plan renders as an empty string.
pub fn render(plan: &Plan, repo_root: &Path) -> String {
    if plan.steps.is_empty() {
        return String::new();
    }
    let mut out = format!(
        "#!/bin/sh\n\
         # Generated by quickpick: sync {} from {} ({}) onto {} ({}).\n\
         set -eu\n\
         cd -- {}\n\
         jj new {}\n",
        plan.path,
        plan.source_rev,
        short(plan.to),
        plan.onto_rev,
        short(plan.onto),
        sh_quote(&repo_root.to_string_lossy()),
        plan.onto,
    );
    for step in &plan.steps {
        match step {
            Step::Pick { commit } => {
                let _ = writeln!(out, "# PICK {} {}", short(commit.id), commit.summary);
                let _ = writeln!(out, "jj duplicate {} -B @", commit.id);
                let msg = cherry_pick_message(commit);
                let delim = heredoc_delim(&msg);
                let _ = writeln!(out, "jj describe @- -m \"$(cat <<'{delim}'");
                out.push_str(&msg);
                let _ = writeln!(out, "{delim}\n)\"");
            }
            Step::Sync {
                target, covered, ..
            } => {
                let _ = writeln!(
                    out,
                    "# SYNC {} ({} {})",
                    short(target.id),
                    covered.len(),
                    if covered.len() == 1 {
                        "commit"
                    } else {
                        "commits"
                    },
                );
                let _ = writeln!(
                    out,
                    "jj restore --from {} {}",
                    target.id,
                    sh_quote(&format!("root:\"{}\"", fileset_escape(&plan.path)))
                );
                let msg = sync_message(plan, step).unwrap_or_default();
                let delim = heredoc_delim(&msg);
                let _ = writeln!(out, "jj describe -m \"$(cat <<'{delim}'");
                out.push_str(&msg);
                let _ = writeln!(out, "{delim}\n)\"");
                let _ = writeln!(out, "jj new");
            }
        }
    }
    out.push_str("jj log -r 'conflicts()'\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::plan::Reason;
    use crate::render::git::tests::sh_check;
    use crate::render::message::tests::{commit, plan};

    fn mixed_plan() -> Plan {
        let mut p = plan("pkgs/by-name/op/openai");
        let pick = commit(0x11, "openai: 1.0 -> 1.1");
        let s1 = commit(0x12, "openai: 1.1 -> 1.2");
        let s2 = commit(0x13, "openai: 1.2 -> 1.3");
        p.steps = vec![
            Step::Pick { commit: pick },
            Step::Sync {
                target: s2.clone(),
                covered: vec![(s1, Reason::OutsidePaths(vec!["other".into()]))],
                removes_path: false,
            },
        ];
        p
    }

    #[test]
    fn full_script_for_a_mixed_plan() {
        let script = render(&mixed_plan(), Path::new("/tmp/repo"));
        let expected = "\
#!/bin/sh
# Generated by quickpick: sync pkgs/by-name/op/openai from master (0000004) onto release-26.05 (0000002).
set -eu
cd -- '/tmp/repo'
jj new 0000002000000000000000000000000000000000
# PICK 0000011 openai: 1.0 -> 1.1
jj duplicate 0000011000000000000000000000000000000000 -B @
jj describe @- -m \"$(cat <<'QUICKPICK_EOF'
openai: 1.0 -> 1.1

(cherry picked from commit 0000011000000000000000000000000000000000)
QUICKPICK_EOF
)\"
# SYNC 0000013 (1 commit)
jj restore --from 0000013000000000000000000000000000000000 'root:\"pkgs/by-name/op/openai\"'
jj describe -m \"$(cat <<'QUICKPICK_EOF'
openai: sync to 0000013 (openai: 1.2 -> 1.3)

Not cherry-picked. Sets pkgs/by-name/op/openai to its state at
0000013000000000000000000000000000000000 on master, replacing these source commits:

  0000012 openai: 1.1 -> 1.2
          touches files outside the path: other

Generated by quickpick.
QUICKPICK_EOF
)\"
jj new
jj log -r 'conflicts()'
";
        assert_eq!(script, expected);
        sh_check(&script);
    }

    #[test]
    fn eof_line_in_a_commit_message_bumps_the_delimiter() {
        let mut p = plan("pkg");
        p.steps = vec![Step::Pick {
            commit: commit(0x20, "subject\n\nQUICKPICK_EOF\n"),
        }];
        let script = render(&p, Path::new("/r"));
        assert!(script.contains("<<'QUICKPICK_EOF_1'"), "{script}");
        sh_check(&script);
    }

    #[test]
    fn fileset_escapes_quotes() {
        let mut p = plan("we\"ird");
        p.steps = vec![Step::Sync {
            target: commit(0x9, "t"),
            covered: vec![],
            removes_path: false,
        }];
        let script = render(&p, Path::new("/r"));
        assert!(script.contains(r#"'root:"we\"ird"'"#), "{script}");
        sh_check(&script);
    }

    #[test]
    fn empty_plan_is_empty_script() {
        assert_eq!(render(&plan("pkg"), Path::new("/r")), "");
    }
}
